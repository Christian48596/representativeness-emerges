def infer_input_type(path: Path) -> str:
    """Infer whether the input is a CSV numerical map or an image."""
    ext = path.suffix.lower()
    if ext in [".csv", ".txt", ".dat"]:
        return "csv"
    if ext in [".tif", ".tiff", ".png", ".jpg", ".jpeg", ".bmp"]:
        return "image"
    raise ValueError(f"Cannot infer input type from extension: {path}")


def maybe_downsample_array(arr: np.ndarray, max_side: int, order: int = 1):
    """
    Downsample a 2D array so max(H,W) <= max_side.

    order=1 is bilinear for scalar fields. For masks use order=0.
    """
    H, W = arr.shape
    if max_side is None or max_side <= 0:
        return arr, 1.0
    scale = max(H, W) / float(max_side)
    if scale <= 1.0:
        return arr, 1.0
    new_H = max(1, int(round(H / scale)))
    new_W = max(1, int(round(W / scale)))
    zH = new_H / float(H)
    zW = new_W / float(W)
    out = zoom(arr, (zH, zW), order=order)
    return out.astype(np.float32, copy=False), scale


def load_scalar_field(path, input_type="auto", max_side=0):
    """
    Load one scalar field from an image or CSV numerical map.

    Image files are converted to grayscale intensity. CSV files are loaded as
    numerical property maps and must already contain physical values if physical
    units are desired downstream.
    """
    path = Path(path)
    if input_type == "auto":
        input_type = infer_input_type(path)

    if input_type == "image":
        img = Image.open(path).convert("L")
        w0, h0 = img.size
        arr = np.asarray(img, dtype=np.float32)
        arr, scale = maybe_downsample_array(arr, max_side=max_side, order=1)
        meta = {
            "input_type": "image",
            "original_width": w0,
            "original_height": h0,
            "analysis_width": arr.shape[1],
            "analysis_height": arr.shape[0],
            "downsample_scale": scale,
        }
        return arr, meta

    if input_type == "csv":
        arr = np.loadtxt(path, delimiter=",").astype(np.float32)
        if arr.ndim != 2:
            raise ValueError(f"CSV map must be 2D: {path}")
        h0, w0 = arr.shape
        arr, scale = maybe_downsample_array(arr, max_side=max_side, order=1)
        meta = {
            "input_type": "csv",
            "original_width": w0,
            "original_height": h0,
            "analysis_width": arr.shape[1],
            "analysis_height": arr.shape[0],
            "downsample_scale": scale,
        }
        return arr, meta

    raise ValueError("input_type must be auto, image, or csv")


def robust_median_mad(arr, eps=1e-12):
    """Return median and MAD-based robust scale."""
    finite = np.isfinite(arr)
    if not np.any(finite):
        return 0.0, 1.0
    vals = arr[finite]
    med = float(np.median(vals))
    mad = float(np.median(np.abs(vals - med)))
    scale = 1.4826 * mad
    if not np.isfinite(scale) or scale < eps:
        scale = float(np.std(vals))
    if not np.isfinite(scale) or scale < eps:
        scale = 1.0
    return med, scale


def transform_field(arr, mode="raw", eps=1e-12):
    """
    Transform the scalar field before stationarity detection.

    raw       : use field directly.
    log       : use log(field + offset). Useful for positive contrast fields.
    robust-z  : use robust z-score (median/MAD).
    log-z     : log transform followed by robust z-score.
    """
    arr = np.asarray(arr, dtype=np.float32)
    out = arr.copy()

    if mode == "raw":
        return out

    if mode in ["log", "log-z"]:
        finite = np.isfinite(out)
        if not np.any(finite):
            raise ValueError("Cannot log-transform a field with no finite values.")
        min_val = float(np.nanmin(out[finite]))
        # Shift only if needed. This keeps physical positive maps essentially unchanged.
        shift = 0.0
        if min_val <= 0.0:
            shift = -min_val + eps
        out = np.log(out + shift + eps).astype(np.float32)
        if mode == "log":
            return out

    if mode in ["robust-z", "log-z"]:
        med, scale = robust_median_mad(out, eps=eps)
        out = ((out - med) / scale).astype(np.float32)
        return out

    raise ValueError("field-transform must be raw, log, robust-z, or log-z")


def robust_standardize_for_combined(arr, transform="raw", eps=1e-12):
    """Transform and robust-standardize one channel for combined masks."""
    if transform == "raw":
        tmp = np.asarray(arr, dtype=np.float32)
    elif transform == "log":
        tmp = transform_field(arr, mode="log", eps=eps)
    else:
        raise ValueError("combined channel transform must be raw or log")
    med, scale = robust_median_mad(tmp, eps=eps)
    return ((tmp - med) / scale).astype(np.float32)


def build_combined_field(kappa, E, nu, combined_transform="log-robust", eps=1e-12):
    """
    Build one scalar stationarity field from kappa/E/nu maps.

    raw-robust: robust-standardize kappa, E, nu directly.
    log-robust: log-transform kappa and E before robust standardization;
                nu is robust-standardized directly because it is dimensionless
                and usually bounded.

    The combined scalar is the Euclidean magnitude of the standardized channels,
    divided by sqrt(Nchannels). This produces one strict structural field sensitive
    to changes in any property channel.
    """
    channels = []
    if combined_transform == "raw-robust":
        channels.append(robust_standardize_for_combined(kappa, transform="raw", eps=eps))
        channels.append(robust_standardize_for_combined(E, transform="raw", eps=eps))
        channels.append(robust_standardize_for_combined(nu, transform="raw", eps=eps))
    elif combined_transform == "log-robust":
        channels.append(robust_standardize_for_combined(kappa, transform="log", eps=eps))
        channels.append(robust_standardize_for_combined(E, transform="log", eps=eps))
        channels.append(robust_standardize_for_combined(nu, transform="raw", eps=eps))
    else:
        raise ValueError("combined-transform must be raw-robust or log-robust")

    stack = np.stack(channels, axis=0)
    return np.sqrt(np.nanmean(stack * stack, axis=0)).astype(np.float32)


def load_property_set(args, index):
    """
    Load one kappa/E/nu property-map set and return the stationarity field.
    """
    kappa = E = nu = None
    meta0 = None

    if args.kappa_maps:
        kappa, meta0 = load_scalar_field(args.kappa_maps[index], input_type="csv", max_side=args.max_side)
    if args.E_maps:
        E, metaE = load_scalar_field(args.E_maps[index], input_type="csv", max_side=args.max_side)
        if meta0 is None:
            meta0 = metaE
    if args.nu_maps:
        nu, metaNu = load_scalar_field(args.nu_maps[index], input_type="csv", max_side=args.max_side)
        if meta0 is None:
            meta0 = metaNu

    source = args.stationarity_source
    if source == "kappa":
        if kappa is None:
            raise ValueError("--stationarity-source kappa requires --kappa-maps")
        field = transform_field(kappa, mode=args.field_transform)
        stem = Path(args.kappa_maps[index]).stem
    elif source == "E":
        if E is None:
            raise ValueError("--stationarity-source E requires --E-maps")
        field = transform_field(E, mode=args.field_transform)
        stem = Path(args.E_maps[index]).stem
    elif source == "nu":
        if nu is None:
            raise ValueError("--stationarity-source nu requires --nu-maps")
        field = transform_field(nu, mode=args.field_transform)
        stem = Path(args.nu_maps[index]).stem
    elif source == "combined":
        if kappa is None or E is None or nu is None:
            raise ValueError("--stationarity-source combined requires --kappa-maps, --E-maps, and --nu-maps")
        if not (kappa.shape == E.shape == nu.shape):
            raise ValueError(
                f"Property maps at index {index+1} have different shapes: "
                f"kappa={kappa.shape}, E={E.shape}, nu={nu.shape}"
            )
        field = build_combined_field(kappa, E, nu, combined_transform=args.combined_transform)
        stem = f"property_combined_{index+1}"
    else:
        raise ValueError("stationarity-source must be kappa, E, nu, or combined")

    return field, meta0, stem


