def process_field(field, stem, meta, args, output_dir):
    """Compute and save stationary mask for one scalar field."""
    print("\nLoaded field")
    print("=" * 80)
    print(f"Field/stem                    : {stem}")
    print(f"Input type                    : {meta.get('input_type', 'property-set')}")
    print(f"Original size                 : {meta['original_width']} x {meta['original_height']} pixels")
    print(f"Analysis size                 : {meta['analysis_width']} x {meta['analysis_height']} pixels")
    print(f"Downsample scale              : {meta['downsample_scale']:.6g}")
    print(f"Stationarity window           : {args.stationarity_window} analysis pixels")
    print(f"Stride                        : {args.stride} analysis pixels")
    print(f"tau_mu                        : {args.tau_mu}")
    print(f"tau_sigma                     : {args.tau_sigma}")
    print("=" * 80)

    centers_y, centers_x, means, stds = compute_window_stats_fast(
        field, R=args.stationarity_window, stride=args.stride
    )
    stat_raw, mu_res, std_res, mu_ref, std_ref = robust_stationary_grid(
        means, stds, tau_mu=args.tau_mu, tau_sigma=args.tau_sigma
    )
    stat_clean = clean_stationary_grid(
        stat_raw,
        min_component_windows=args.min_component_windows,
        do_open_close=(not args.no_morphology),
    )
    mask = grid_to_pixel_mask(
        stat_clean,
        image_shape=field.shape,
        centers_y=centers_y,
        centers_x=centers_x,
        R=args.stationarity_window,
    )
    if args.keep_largest_component:
        mask = largest_component(mask)

    stat_fraction_grid = float(stat_clean.mean())
    stat_fraction_pixel = float(mask.mean())

    print("Stationary-domain result")
    print("-" * 80)
    print(f"Reference local mean          : {mu_ref:.8g}")
    print(f"Reference local std           : {std_ref:.8g}")
    print(f"Accepted grid-window fraction : {stat_fraction_grid:.8g}")
    print(f"Accepted pixel fraction       : {stat_fraction_pixel:.8g}")
    print("-" * 80)

    mask_png = output_dir / f"{stem}_stationary_mask.png"
    mask_tif = output_dir / f"{stem}_stationary_mask.tif"
    overlay_png = output_dir / f"{stem}_stationary_overlay.png"
    summary_png = output_dir / f"{stem}_stationary_summary.png"
    csv_path = output_dir / f"{stem}_stationary_windows.csv"

    save_mask_png(mask, mask_png)
    save_mask_tif(mask, mask_tif)
    save_overlay(field, mask, overlay_png, title=f"{stem}: stationary-domain mask", dpi=args.dpi, cmap=args.cmap)
    save_summary_plot(field, mask, means, stds, mu_res, std_res, stat_clean,
                      summary_png, title=f"{stem}: stationarity diagnostics", dpi=args.dpi, cmap=args.cmap)
    save_grid_diagnostics_csv(csv_path, centers_y, centers_x, means, stds, mu_res, std_res, stat_raw, stat_clean)

    return {
        "field": stem,
        "analysis_height": field.shape[0],
        "analysis_width": field.shape[1],
        "downsample_scale": meta["downsample_scale"],
        "stationarity_window": args.stationarity_window,
        "stride": args.stride,
        "tau_mu": args.tau_mu,
        "tau_sigma": args.tau_sigma,
        "mu_ref": mu_ref,
        "std_ref": std_ref,
        "stationary_grid_fraction": stat_fraction_grid,
        "stationary_pixel_fraction": stat_fraction_pixel,
        "mask_png": str(mask_png),
        "mask_tif": str(mask_tif),
        "overlay_png": str(overlay_png),
        "summary_png": str(summary_png),
        "csv": str(csv_path),
    }


def save_global_summary(rows, output_dir):
    path = output_dir / "stationary_domain_global_summary.csv"
    keys = [
        "field", "analysis_height", "analysis_width", "downsample_scale",
        "stationarity_window", "stride", "tau_mu", "tau_sigma", "mu_ref", "std_ref",
        "stationary_grid_fraction", "stationary_pixel_fraction",
        "mask_png", "mask_tif", "overlay_png", "summary_png", "csv",
    ]
    with open(path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
    print("\nSaved global summary:")
    print(f"  {path}")


