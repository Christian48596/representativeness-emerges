#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
General stationary-domain detector for microscopy images and numerical property maps.

Purpose
-------
This script creates strict stationary-domain masks before any REV calculation.
It generalizes the previous BSE/gray-image mask detector so that the same idea
can be applied to numerical property fields such as

    kappa(x,y) [W m^-1 K^-1], E(x,y) [GPa], nu(x,y) [-]

stored as CSV maps, or to ordinary image files such as TIFF/PNG BSE maps.

Scientific logic
----------------
For a scalar field Z(x,y), the code scans the full map with local square
stationarity windows of side R. For each stationarity window W_p it computes

    mu_p    = mean(Z in W_p)
    sigma_p = std(Z in W_p)

The robust image-level references are the medians of all local means and local
standard deviations. A stationarity window is accepted when both normalized
residuals satisfy the prescribed tolerances:

    |mu_p - median(mu)|       / (|median(mu)|    + eps) <= tau_mu
    |sigma_p - median(sigma)| / (|median(sigma)| + eps) <= tau_sigma

Accepted stationarity windows are converted into a pixel-level mask. Small
isolated components can be removed, and optionally only the largest connected
component can be retained.

Input modes
-----------
1. Single-field mode:
       python detect_stationary_domains_general.py field1.csv field2.csv ...

   Use this for BSE images, kappa maps, E maps, or nu maps separately.

2. Property-map mode:
       python detect_stationary_domains_general.py \
           --kappa-maps kappaMap_1.csv ... kappaMap_7.csv \
           --E-maps     EMap_1.csv     ... EMap_7.csv     \
           --nu-maps    nuMap_1.csv    ... nuMap_7.csv    \
           --stationarity-source combined

   Use this to build masks on the property-map grid. The stationarity source
   can be kappa, E, nu, or combined. For combined, the code robustly standardizes
   each available channel and combines them into a scalar structural field.

Important notes
---------------
* Use CSV numerical property maps, not TIFF visualization maps generated by
  mat2gray/imwrite. TIFF visualization maps are rescaled intensities and do not
  preserve physical units.
* For kappa and E, a log transform is often useful because material contrasts can
  span large ranges. Use --field-transform log for single-field mode, or use
  --combined-transform log-robust for combined property-map mode.
* The output mask is on the same grid as the input field used for stationarity.
  Therefore, for QEMSCAN-derived property maps, the mask is directly defined on
  the property-map grid.

Examples
--------
BSE/gray images, full resolution:
    python detect_stationary_domains_general.py \
        1_cut.tif 2_cut.tif 3_cut.tif 4_cut.tif 5_cut.tif 6_cut.tif 7_cut.tif \
        --output-dir stationary_BSE_STRICT \
        --input-type image \
        --stationarity-window 2048 \
        --stride 512 \
        --tau-mu 0.02 \
        --tau-sigma 0.06

Kappa CSV maps on property grid:
    python detect_stationary_domains_general.py \
        data/conductivity/kappaMap_1.csv ... data/conductivity/kappaMap_7.csv \
        --output-dir stationary_kappa_STRICT \
        --input-type csv \
        --field-transform log \
        --stationarity-window 256 \
        --stride 64 \
        --tau-mu 0.02 \
        --tau-sigma 0.06

Combined kappa/E/nu property masks:
    python detect_stationary_domains_general.py \
        --kappa-maps data/conductivity/kappaMap_1.csv ... data/conductivity/kappaMap_7.csv \
        --E-maps "data/Young modulus/EMap_1.csv" ... "data/Young modulus/EMap_7.csv" \
        --nu-maps "data/Poisson ratio/nuMap_1.csv" ... "data/Poisson ratio/nuMap_7.csv" \
        --stationarity-source combined \
        --combined-transform log-robust \
        --output-dir stationary_property_combined_STRICT \
        --stationarity-window 256 \
        --stride 64 \
        --tau-mu 0.02 \
        --tau-sigma 0.06
"""

