def integral_image(arr):
    """Integral image with zero padding."""
    arr = np.asarray(arr, dtype=np.float64)
    return np.pad(arr.cumsum(axis=0).cumsum(axis=1), ((1, 0), (1, 0)), mode="constant")


def window_sum(ii, y0, x0, y1, x1):
    """Sum over arr[y0:y1, x0:x1] from integral image."""
    return ii[y1, x1] - ii[y0, x1] - ii[y1, x0] + ii[y0, x0]


def compute_window_stats_fast(img, R, stride):
    """
    Compute local mean/std on a regular grid of R x R windows.

    NaN/inf values are replaced by the finite median before scanning. This keeps
    the integral-image calculation fast and avoids undefined local statistics.
    """
    img = np.asarray(img, dtype=np.float32)
    finite = np.isfinite(img)
    if not np.any(finite):
        raise ValueError("Input field contains no finite values.")
    if not np.all(finite):
        med = np.nanmedian(img[finite])
        img = img.copy()
        img[~finite] = med

    H, W = img.shape
    if R > H or R > W:
        raise ValueError(f"stationarity-window R={R} is larger than image size {H} x {W}")

    y_starts = list(range(0, H - R + 1, stride))
    x_starts = list(range(0, W - R + 1, stride))
    if not y_starts or not x_starts:
        raise ValueError("No stationarity windows generated. Check R and stride.")
    if y_starts[-1] != H - R:
        y_starts.append(H - R)
    if x_starts[-1] != W - R:
        x_starts.append(W - R)

    ii = integral_image(img)
    ii2 = integral_image(img * img)
    means = np.zeros((len(y_starts), len(x_starts)), dtype=np.float64)
    stds = np.zeros_like(means)
    area = float(R * R)

    for iy, y0 in enumerate(y_starts):
        y1 = y0 + R
        for ix, x0 in enumerate(x_starts):
            x1 = x0 + R
            s1 = window_sum(ii, y0, x0, y1, x1)
            s2 = window_sum(ii2, y0, x0, y1, x1)
            mu = s1 / area
            var = max(s2 / area - mu * mu, 0.0)
            means[iy, ix] = mu
            stds[iy, ix] = np.sqrt(var)

    centers_y = np.array(y_starts, dtype=float) + 0.5 * R
    centers_x = np.array(x_starts, dtype=float) + 0.5 * R
    return centers_y, centers_x, means, stds


def robust_stationary_grid(means, stds, tau_mu=0.03, tau_sigma=0.08, eps=1e-12):
    """Classify coarse stationarity windows using median references."""
    mu_ref = np.nanmedian(means)
    std_ref = np.nanmedian(stds)
    mu_res = np.abs(means - mu_ref) / (abs(mu_ref) + eps)
    std_res = np.abs(stds - std_ref) / (abs(std_ref) + eps)
    stat_grid = (mu_res <= tau_mu) & (std_res <= tau_sigma)
    return stat_grid, mu_res, std_res, mu_ref, std_ref


def clean_stationary_grid(stat_grid, min_component_windows=4, do_open_close=True):
    """Morphological cleanup and connected-component filtering on coarse grid."""
    if stat_grid.size == 0:
        return stat_grid
    cleaned = stat_grid.astype(bool)
    if do_open_close:
        cleaned = binary_opening(cleaned, structure=np.ones((2, 2), dtype=bool))
        cleaned = binary_closing(cleaned, structure=np.ones((2, 2), dtype=bool))
    if min_component_windows <= 1:
        return cleaned
    lab, nlab = label(cleaned)
    out = np.zeros_like(cleaned, dtype=bool)
    for k in range(1, nlab + 1):
        comp = lab == k
        if comp.sum() >= min_component_windows:
            out |= comp
    return out


def grid_to_pixel_mask(stat_grid, image_shape, centers_y, centers_x, R):
    """Convert accepted coarse stationarity windows to a pixel-level mask."""
    H, W = image_shape
    mask = np.zeros((H, W), dtype=bool)
    for iy, cy in enumerate(centers_y):
        for ix, cx in enumerate(centers_x):
            if not stat_grid[iy, ix]:
                continue
            y0 = int(round(cy - 0.5 * R))
            x0 = int(round(cx - 0.5 * R))
            y1 = min(y0 + R, H)
            x1 = min(x0 + R, W)
            y0 = max(y0, 0)
            x0 = max(x0, 0)
            mask[y0:y1, x0:x1] = True
    return mask


def largest_component(mask):
    """Keep the largest connected component of a pixel mask."""
    lab, nlab = label(mask)
    if nlab == 0:
        return mask
    sizes = np.array([(lab == k).sum() for k in range(1, nlab + 1)])
    kmax = int(np.argmax(sizes)) + 1
    return lab == kmax


