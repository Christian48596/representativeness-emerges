def save_mask_tif(mask, path):
    Image.fromarray(mask.astype(np.uint8) * 255).save(path)


def save_mask_png(mask, path):
    Image.fromarray(mask.astype(np.uint8) * 255).save(path)


def save_overlay(field, mask, path, title=None, dpi=300, cmap="gray"):
    """Save field with red stationary-mask overlay."""
    fig, ax = plt.subplots(figsize=(8, 7))
    im = ax.imshow(field, cmap=cmap, origin="upper")
    overlay = np.zeros((*mask.shape, 4), dtype=float)
    overlay[..., 0] = 1.0
    overlay[..., 3] = mask.astype(float) * 0.35
    ax.imshow(overlay, origin="upper")
    if title:
        ax.set_title(title)
    ax.set_xlabel("x [analysis pixels]")
    ax.set_ylabel("y [analysis pixels]")
    cbar = fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    cbar.set_label("stationarity field value")
    fig.tight_layout()
    fig.savefig(path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


def save_grid_diagnostics_csv(path, centers_y, centers_x, means, stds, mu_res, std_res, stat_raw, stat_clean):
    """Save local stationarity-window diagnostics."""
    with open(path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "iy", "ix", "center_y", "center_x", "mean", "std",
            "mu_residual", "std_residual", "stationary_raw", "stationary_clean",
        ])
        for iy, cy in enumerate(centers_y):
            for ix, cx in enumerate(centers_x):
                writer.writerow([
                    iy, ix, float(cy), float(cx), float(means[iy, ix]), float(stds[iy, ix]),
                    float(mu_res[iy, ix]), float(std_res[iy, ix]),
                    int(stat_raw[iy, ix]), int(stat_clean[iy, ix]),
                ])


def save_summary_plot(field, mask, means, stds, mu_res, std_res, stat_clean, output_path, title, dpi=300, cmap="gray"):
    """Save four-panel diagnostic summary for one field."""
    fig, axes = plt.subplots(2, 2, figsize=(11, 9))

    ax = axes[0, 0]
    im0 = ax.imshow(field, cmap=cmap, origin="upper")
    ax.set_title("Input stationarity field")
    ax.set_xlabel("x")
    ax.set_ylabel("y")
    fig.colorbar(im0, ax=ax, shrink=0.80)

    ax = axes[0, 1]
    ax.imshow(field, cmap=cmap, origin="upper")
    overlay = np.zeros((*mask.shape, 4), dtype=float)
    overlay[..., 0] = 1.0
    overlay[..., 3] = mask.astype(float) * 0.35
    ax.imshow(overlay, origin="upper")
    ax.set_title("Stationary-domain mask")
    ax.set_xlabel("x")
    ax.set_ylabel("y")

    ax = axes[1, 0]
    im = ax.imshow(means, origin="upper", aspect="auto")
    if np.any(stat_clean):
        ax.contour(stat_clean.astype(float), levels=[0.5], colors="white", linewidths=1.0)
    fig.colorbar(im, ax=ax, shrink=0.85)
    ax.set_title("Local window mean")
    ax.set_xlabel("window-grid x")
    ax.set_ylabel("window-grid y")

    ax = axes[1, 1]
    combined_res = np.maximum(mu_res, std_res)
    im = ax.imshow(combined_res, origin="upper", aspect="auto")
    if np.any(stat_clean):
        ax.contour(stat_clean.astype(float), levels=[0.5], colors="white", linewidths=1.0)
    fig.colorbar(im, ax=ax, shrink=0.85)
    ax.set_title("Max normalized residual")
    ax.set_xlabel("window-grid x")
    ax.set_ylabel("window-grid y")

    fig.suptitle(title)
    fig.tight_layout()
    fig.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(fig)


